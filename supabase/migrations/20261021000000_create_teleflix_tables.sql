create table if not exists public.users (
  id integer generated by default as identity primary key,
  uid text not null unique,
  email text not null,
  display_name text,
  photo_url text,
  telegram_api_key text,
  telegram_bot_token text,
  telegram_api_hash text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create table if not exists public.channels (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users(id) on delete cascade,
  channel_username text not null,
  title text not null,
  category text default 'Movies & Shows',
  description text,
  avatar_url text,
  subscriber_count text,
  is_monetized boolean default false,
  ad_network text default 'Direct Sponsorship',
  created_at timestamptz default now(),
  unique (user_id, channel_username)
);

create table if not exists public.favorites (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users(id) on delete cascade,
  media_id text not null,
  title text not null,
  channel text not null,
  type text not null,
  video_url text,
  poster text,
  backdrop text,
  caption text,
  created_at timestamptz default now(),
  unique (user_id, media_id)
);

create table if not exists public.telegram_login_codes (
  code_hash text primary key,
  uid text not null references public.users(uid) on delete cascade,
  display_name text not null,
  photo_url text,
  username text,
  expires_at timestamptz not null,
  consumed_at timestamptz,
  created_at timestamptz not null default now()
);

alter table public.users enable row level security;
alter table public.channels enable row level security;
alter table public.favorites enable row level security;
alter table public.telegram_login_codes enable row level security;

revoke all on table public.users, public.channels, public.favorites, public.telegram_login_codes from anon, authenticated;
grant all on table public.users, public.channels, public.favorites, public.telegram_login_codes to service_role;
grant usage, select on all sequences in schema public to service_role;
