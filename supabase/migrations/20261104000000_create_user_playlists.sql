create table if not exists public.user_playlists (
  id bigint generated by default as identity primary key,
  user_id integer not null references public.users(id) on delete cascade,
  playlist_id text not null,
  name text not null check (char_length(name) between 1 and 60),
  item_ids text[] not null default '{}',
  created_at bigint not null,
  updated_at timestamptz not null default now(),
  unique (user_id, playlist_id)
);

create index if not exists user_playlists_user_updated_idx
  on public.user_playlists (user_id, updated_at desc);

alter table public.user_playlists enable row level security;
revoke all on table public.user_playlists from anon, authenticated;
grant all on table public.user_playlists to service_role;
grant usage, select on sequence public.user_playlists_id_seq to service_role;
